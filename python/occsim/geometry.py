from __future__ import annotations

import math
from pathlib import Path

VERSION_LINE = "# occupancy-sim scaffold geometry v1"

# The printed M-Alg scaffold is a square lattice of extruded strands with open
# pores between them (Li 2025, Figure 2D-G). Strand pitch there is order 600 um
# at the print scale, which is what `lattice` reproduces; `disc` and `square`
# are simple controls for isolating the effect of scaffold AREA from scaffold
# SHAPE.
SHAPES = ("lattice", "disc", "square")
DEFAULT_STRAND_PITCH_UM = 600.0


def _compartment_centres(grid: int, field_um: float):
    #Compartment centres in field coordinates, origin at the middle.
    comp_um = field_um / grid
    return [(i + 0.5) * comp_um - field_um / 2 for i in range(grid)]


def _scores(shape: str, grid: int, field_um: float, strand_pitch_um: float):
    #Per-compartment scaffold-membership score, higher = more scaffold.

    centres = _compartment_centres(grid, field_um)
    if shape == "lattice":
        strand_count = max(1, round(field_um / strand_pitch_um))
        pitch = field_um / strand_count
        # distance from each axis to the nearest strand centreline
        offsets = [abs((c + pitch / 2) % pitch - pitch / 2) for c in centres]
        # closer to a strand on EITHER axis means more scaffold, so the score
        # is the negated smaller of the two distances
        return [-min(offsets[cx], offsets[cy])
                for cy in range(grid) for cx in range(grid)]
    if shape == "disc":
        return [-math.hypot(centres[cx], centres[cy])
                for cy in range(grid) for cx in range(grid)]
    return [-max(abs(centres[cx]), abs(centres[cy]))
            for cy in range(grid) for cx in range(grid)]


def build(shape: str, grid: int, field_um: float, area_fraction: float,
          strand_pitch_um: float = DEFAULT_STRAND_PITCH_UM):
    #Build a scaffold mask covering exactly the requested area fraction.

    if shape not in SHAPES:
        raise ValueError(f"unknown shape {shape!r}, expected one of {SHAPES}")
    if grid < 1:
        raise ValueError(f"grid must be >= 1, got {grid}")
    if not 0 < area_fraction <= 1:
        raise ValueError(
            f"area_fraction must be in (0,1], got {area_fraction}")
    if field_um <= 0:
        raise ValueError(f"field_um must be > 0, got {field_um}")
    if shape == "lattice" and strand_pitch_um <= 0:
        raise ValueError(
            f"strand_pitch_um must be > 0, got {strand_pitch_um}")

    total = grid * grid
    # at least one compartment, or the engine's loader rejects the file
    target = max(1, min(total, round(area_fraction * total)))
    scores = _scores(shape, grid, field_um, strand_pitch_um)
    # Rank by score and take the top k, which is what makes the realised area
    # exact at any grid (a geometric threshold missed a requested 40 % by 8
    # points on a 150x150 lattice).
    centres = _compartment_centres(grid, field_um)
    def radius(i):
        return math.hypot(centres[i % grid], centres[i // grid])
    order = sorted(range(total), key=lambda i: (-scores[i], radius(i), i))
    mask = [0] * total
    for i in order[:target]:
        mask[i] = 1
    return mask


def write(path: Path, mask, grid: int, field_um: float, provenance: str
          ) -> float:
    #Write a mask as a geometry CSV.
    scaffold_count = sum(mask)
    if scaffold_count == 0:
        raise ValueError(
            "no compartment came out as scaffold - the area fraction is too "
            "small for this grid, so raise --area-frac or --grid")
    lines = [VERSION_LINE,
             f"# {provenance}",
             "# GENERATED by occsim, not measured data.",
             f"grid,{grid},{grid}",
             f"scaffold_um,{field_um:g}",
             "cx,cy,scaffold"]
    for cy in range(grid):
        for cx in range(grid):
            lines.append(f"{cx},{cy},{mask[cy * grid + cx]}")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n")
    return scaffold_count / float(grid * grid)


def ensure(out_dir: Path, shape: str, grid: int, field_um: float,
           area_fraction: float,
           strand_pitch_um: float = DEFAULT_STRAND_PITCH_UM) -> Path:
    #Build the scaffold mask for a run, writing it where the run's output goes.

    mask = build(shape, grid, field_um, area_fraction, strand_pitch_um)
    pct = round(100 * area_fraction, 2)
    # Pitch only affects a lattice, so putting it in the name for other shapes
    # would invent a distinction the mask does not have.
    pitch = f"_pitch{strand_pitch_um:g}" if shape == "lattice" else ""
    path = (Path(out_dir) / "geometry"
            / f"scaffold_{shape}_{grid}x{grid}_{pct:g}pct"
              f"_{field_um:g}um{pitch}.csv")
    provenance = (f"occsim --scaffold-shape {shape} "
                  f"--scaffold-area-frac {area_fraction:g} "
                  f"--compartments {grid} --field {field_um:g}"
                  + (f" --strand-pitch {strand_pitch_um:g}"
                     if shape == "lattice" else ""))
    write(path, mask, grid, field_um, provenance)
    return path
